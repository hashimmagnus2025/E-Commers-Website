export function searchProducts(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return products.filter((p) =>
    [p.name, p.category, p.department, p.collection, p.description, ...p.colors.map((c) => c.name)]
      .join(" ")
      .toLowerCase()
      .includes(q) || (q.endsWith("s") && p.category.toLowerCase() === q.slice(0, -1)),
  );
}
