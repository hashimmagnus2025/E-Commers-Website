export const getRelated = (product: Product, count = 4) => {
  const same = products.filter((p) => p.id !== product.id && p.department === product.department);
  const others = products.filter((p) => p.id !== product.id && p.department !== product.department);
  return [...same, ...others].slice(0, count);
};

